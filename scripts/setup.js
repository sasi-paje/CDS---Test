// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });

  const bold  = s => `\x1b[1m${s}\x1b[0m`;
  const cyan  = s => `\x1b[36m${s}\x1b[0m`;
  const green = s => `\x1b[32m${s}\x1b[0m`;
  const dim   = s => `\x1b[2m${s}\x1b[0m`;

  console.log(`\n${bold(cyan('Custom Design System — Project Setup'))}\n`);
  console.log('Answers get written to project.config.json and CLAUDE.md.');
  console.log('Claude Code reads CLAUDE.md automatically — your choices become binding rules.\n');

  // ── 1. Project name ──────────────────────────────────────────────────────────
  const name = (await ask(rl, `${bold('1.')} Project name: `)) || 'My Project';

  // ── 2. Brand ─────────────────────────────────────────────────────────────────
  console.log(`\n${bold('2.')} Brand hue:`);
  BRANDS.forEach((b, i) =>
    console.log(`   ${String(i + 1).padStart(2)}.  ${b.name.padEnd(10)}  ${dim(b.hex)}`)
  );
  console.log(`   ${String(BRANDS.length + 1).padStart(2)}.  ${dim('Custom hex color')}`)
  const brandChoice = await ask(rl, `   Choose [1-${BRANDS.length + 1}, default 1]: `);

  let brand, customHueName;
  const brandN = parseInt(brandChoice, 10);
  if (brandN === BRANDS.length + 1) {
    const rawHex = await ask(rl, '   Hex value (e.g. #3a7bd5): ');
    customHueName = (await ask(rl, '   Name for this hue (lowercase, no spaces, e.g. ocean): '))
      .toLowerCase().replace(/[^a-z0-9-]/g, '-') || 'custom';
    brand = customHueName;
    // Validate + generate scale later
    const scale = generateScale(rawHex);
    if (!scale) {
      console.log(`   ${dim('Invalid hex — falling back to indigo')}`);
      brand = 'indigo';
      customHueName = null;
    } else {
      console.log(`   Generating scale for ${bold(customHueName)}...`);
      injectCustomBrand(customHueName, scale);
      console.log(`   ✓ Added to src/whitelabel/tokens.css`);
    }
  } else {
    brand = (pickFromList(brandChoice, BRANDS, 0)).name;
  }

  // ── 3. Style preset ──────────────────────────────────────────────────────────
  console.log(`\n${bold('3.')} Style preset:`);
  STYLES.forEach((s, i) =>
    console.log(`   ${i + 1}.  ${s.name.padEnd(12)}  ${s.font.padEnd(20)}  ${dim(s.desc)}`)
  );
  const styleChoice = await ask(rl, '   Choose [1-5, default 1]: ');
  const style = (pickFromList(styleChoice, STYLES, 0)).name;

  // ── 4. Default theme ─────────────────────────────────────────────────────────
  console.log(`\n${bold('4.')} Default theme:`);
  console.log('   1.  light  (recommended — dark is always available at runtime)');
  console.log('   2.  dark');
  const themeChoice = await ask(rl, '   Choose [1-2, default 1]: ');
  const theme = themeChoice === '2' ? 'dark' : 'light';

  // ── 5. Default component size ─────────────────────────────────────────────────
  console.log(`\n${bold('5.')} Default component size:`);
  SIZES.forEach((s, i) =>
    console.log(`   ${i + 1}.  ${s.name.padEnd(4)}  ${dim(s.desc)}`)
  );
  const sizeChoice = await ask(rl, '   Choose [1-4, default 3 = md]: ');
  const size = (pickFromList(sizeChoice, SIZES, 2)).name;

  // ── 6. Font override ──────────────────────────────────────────────────────────
  const styleInfo = STYLES.find(s => s.name === style);
  const presetFont = styleInfo ? styleInfo.font.replace(' (tabular)', '') : 'Inter';
  console.log(`\n${bold('6.')} Font — the ${bold(style)} preset uses ${bold(presetFont)} by default.`);
  console.log('   1.  Use preset default  (recommended)');
  console.log('   2.  Inter');
  console.log('   3.  IBM Plex Sans');
  console.log('   4.  DM Sans');
  console.log('   5.  Geist');
  const fontChoice = await ask(rl, '   Choose [1-5, default 1]: ');
  const fontMap = { '2': 'Inter', '3': 'IBM Plex Sans', '4': 'DM Sans', '5': 'Geist' };
  const font = fontMap[fontChoice] || null;

  rl.close();

  // ── Write outputs ─────────────────────────────────────────────────────────────
  const config = { name, brand, style, theme, size, font };

  console.log('');
  process.stdout.write('→ Writing project.config.json... ');
  writeConfig(config);
  console.log('✓');

  process.stdout.write('→ Updating CLAUDE.md...          ');
  updateClaudeMd(config);
  console.log('✓');

  process.stdout.write('→ Generating index.html...       ');
  fs.writeFileSync(path.join(ROOT, 'index.html'), generateStarterHtml(config));
  console.log('✓');

  const resolvedFont = font || presetFont;
  console.log(`\n${bold(green('✓ Setup complete!'))}\n`);
  console.log(`  Project : ${bold(name)}`);
  console.log(`  Brand   : ${brand}`);
  console.log(`  Style   : ${style}`);
  console.log(`  Theme   : ${theme}`);
  console.log(`  Size    : ${size}`);
  console.log(`  Font    : ${resolvedFont}`);
  console.log('');
  console.log('Next steps:');
  console.log('  1. Open index.html in a browser to verify the look.');
  console.log('  2. Run  claude  to start Claude Code — it reads CLAUDE.md automatically.');
  console.log('  3. Re-run  pnpm setup  at any time to change the config.\n');
}

main().catch(err => {
  console.error('\nSetup failed:', err.message);
  process.exit(1);
});
