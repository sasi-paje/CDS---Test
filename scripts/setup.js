// ─── Readline helpers ─────────────────────────────────────────────────────────

function ask(rl, question) {
  return new Promise(resolve => rl.question(question, answer => resolve(answer.trim())));
}

function pickFromList(answer, list, defaultIndex = 0) {
  const n = parseInt(answer, 10);
  if (isNaN(n) || n < 1 || n > list.length) return list[defaultIndex];
  return list[n - 1];
}

// ─── Custom color scale generator ────────────────────────────────────────────

function hexToRgb(hex) {
  const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
  if (!result) return null;
  return { r: parseInt(result[1], 16), g: parseInt(result[2], 16), b: parseInt(result[3], 16) };
}

function rgbToHsl(r, g, b) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  let h = 0, s = 0;
  const l = (max + min) / 2;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    switch (max) {
      case r: h = (g - b) / d + (g < b ? 6 : 0); break;
      case g: h = (b - r) / d + 2; break;
      case b: h = (r - g) / d + 4; break;
    }
    h /= 6;
  }
  return { h: Math.round(h * 360), s: Math.round(s * 100), l: Math.round(l * 100) };
}

function hslToHex(h, s, l) {
  s /= 100; l /= 100;
  const a = s * Math.min(l, 1 - l);
  const f = n => {
    const k = (n + h / 30) % 12;
    const color = l - a * Math.max(Math.min(k - 3, 9 - k, 1), -1);
    return Math.round(255 * color).toString(16).padStart(2, '0');
  };
  return `#${f(0)}${f(8)}${f(4)}`;
}

// Generates a 10-stop perceptual scale from a single hex value.
// Stops: 50 100 200 300 400 500 600 700 800 900
function generateScale(hex) {
  const rgb = hexToRgb(hex);
  if (!rgb) return null;
  const { h, s } = rgbToHsl(rgb.r, rgb.g, rgb.b);

  const stops = [
    { stop: 50,  l: 97, sMult: 0.25 },
    { stop: 100, l: 93, sMult: 0.35 },
    { stop: 200, l: 85, sMult: 0.55 },
    { stop: 300, l: 75, sMult: 0.75 },
    { stop: 400, l: 63, sMult: 0.90 },
    { stop: 500, l: 50, sMult: 1.00 },
    { stop: 600, l: 41, sMult: 0.95 },
    { stop: 700, l: 33, sMult: 0.90 },
    { stop: 800, l: 26, sMult: 0.80 },
    { stop: 900, l: 18, sMult: 0.65 },
  ];

  return stops.map(({ stop, l, sMult }) => ({
    stop,
    hex: hslToHex(h, Math.round(s * sMult), l),
  }));
}

function injectCustomBrand(hueName, scale) {
  const tokenPath = path.join(ROOT, 'src/whitelabel/tokens.css');
  let css = fs.readFileSync(tokenPath, 'utf8');

  const rootVars = scale.map(({ stop, hex }) => `  --${hueName}-${stop}: ${hex};`).join('\n');
  const brandAlias = scale.map(({ stop }) =>
    `--brand-${stop}:var(--${hueName}-${stop})`).join(';');

  const block =
    `/* CUSTOM BRAND: ${hueName} — generated by pnpm setup */\n` +
    `:root {\n${rootVars}\n}\n` +
    `:root[data-brand="${hueName}"] { ${brandAlias}; }\n` +
    `/* END CUSTOM BRAND: ${hueName} */`;

  // Replace existing block for this name (idempotent)
  const re = new RegExp(
    `/\\* CUSTOM BRAND: ${hueName}[\\s\\S]*?/\\* END CUSTOM BRAND: ${hueName} \\*/\\n?`,
    'g'
  );
  css = css.replace(re, '');
  css = css.trimEnd() + '\n\n' + block + '\n';
  fs.writeFileSync(tokenPath, css);
}

// ─── Output file writers ──────────────────────────────────────────────────────

function writeConfig(config) {
  fs.writeFileSync(
    path.join(ROOT, 'project.config.json'),
    JSON.stringify(config, null, 2) + '\n'
  );
}

function updateClaudeMd(config) {
  const claudePath = path.join(ROOT, 'CLAUDE.md');
  let content = fs.readFileSync(claudePath, 'utf8');

  const styleInfo = STYLES.find(s => s.name === config.style);
  const font = config.font || (styleInfo ? styleInfo.font : 'Inter');

  const section =
    `## Project Config\n` +
    `<!-- generated by \`pnpm setup\` — re-run to change -->\n\n` +
    `| Setting | Value |\n` +
    `|---|---|\n` +
    `| Name | ${config.name} |\n` +
    `| Brand | ${config.brand} |\n` +
    `| Style | ${config.style} |\n` +
    `| Theme | ${config.theme} |\n` +
    `| Default size | ${config.size} |\n` +
    `| Font | ${font} |\n\n` +
    `**Binding rules for Claude Code:**\n` +
    `- \`<html>\` must always carry \`data-brand="${config.brand}"\` \`data-style="${config.style}"\` \`data-theme="${config.theme}"\`\n` +
    `- Default component size is \`${config.size}\` — override only when context requires (table headers → \`xs\`/\`sm\`, landing CTAs → \`lg\`)\n` +
    `- Only use components from \`src/whitelabel/\` — never invent new components\n` +
    `- Never reference a raw color scale — only semantic tokens (\`--fg-*\`, \`--bg-*\`, \`--border-*\`, \`--space-*\`)\n` +
    `- One brand, one accent — a second color must come from the status set (success/warning/danger/info)\n` +
    `- Font: ${font}${config.font ? ` (overridden from ${styleInfo?.font})` : ' (set by style preset)'}\n`;

  // Replace existing section (idempotent) or append
  const re = /## Project Config\n[\s\S]*?(?=\n## (?!Project Config)|\n---\s*\n|$)/;
  if (re.test(content)) {
    content = content.replace(re, section.trimEnd());
  } else {
    content = content.trimEnd() + '\n\n' + section;
  }

  fs.writeFileSync(claudePath, content);
}

